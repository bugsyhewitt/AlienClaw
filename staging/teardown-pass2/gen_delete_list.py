#!/usr/bin/env python3
"""Regenerate delete-list.txt for AlienClaw teardown pass 2 from the DROP manifest.

Usage:
    python3 gen_delete_list.py [--repo REPO] [--base BASE] [--manifest JSON] > delete-list.txt

    --repo      any checkout of the AlienClaw repo (default: /home/xil/dev/alienclaw)
    --base      tree the list is checked against (default: origin/main)
    --manifest  the DROP manifest (default: docs/salvage/drop-manifest.json, two levels
                up from this script), generated by staging/tools/build_drop_manifest.py

The manifest is the only source of truth for what pass 2 drops. The list is:

    every file the manifest marks DROP
    + KIT_DECISIONS   files the kit deletes although the manifest says REVIEW or KEEP
    - KIT_KEEPS       manifest-DROP files the kit keeps
    + files pass 1 (#653) adds under a DROP root (manifest "pass1.added_in_pass1"),
      so the list also cleans up a tree where #653 merged first

Output: one path per line, sorted (C order), unique, no comments. It fails (exit 1,
nothing on stdout) when the manifest and the two lists below disagree:
  - a KIT_DECISIONS entry is already DROP in the manifest (stale), is not in the
    manifest, or is missing at BASE
  - a KIT_KEEPS entry is not DROP in the manifest (stale) or is missing at BASE
  - a manifest DROP file is missing at BASE and pass 1 does not delete it (stale
    manifest), or pass 1 deletes a file the list would keep
  - a file that decoupling.patch or ci-pass2.patch edits would be deleted
  - a path contains whitespace (the README applies the list with plain xargs)
A DROP file whose blob at BASE differs from the manifest's is only a warning.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys

KIT_DIR = os.path.dirname(os.path.abspath(__file__))
DEFAULT_REPO = "/home/xil/dev/alienclaw"
DEFAULT_BASE = "origin/main"
DEFAULT_MANIFEST = os.path.join(KIT_DIR, "..", "..", "docs", "salvage", "drop-manifest.json")
PATCHES = ("decoupling.patch", "ci-pass2.patch")

# Files the kit deletes although the manifest does not mark them DROP. Each reason
# says why the file cannot survive the cut. Keep in sync with README "delete-list.txt".
KIT_DECISIONS = {
    # REVIEW in the manifest: tooling for seed/ and site/, both DROP.
    "scripts/check-seed-drift.sh": "drift gate for seed/martians/ (DROP); decoupling.patch"
    " also drops it from package.json `test`",
    "scripts/gen-seed-genomes.py": "regenerates seed/martians/ (DROP)",
    "scripts/deploy.sh": "deploys only the retired site/ (DROP)",
    "scripts/local-preview.sh": "serves only the retired site/ (DROP)",
    # REVIEW in the manifest: Martian experiment drivers.
    "scripts/run_packet25_experiments.py": "imports evolution.bridge_runner (DROP)",
    "scripts/run_packet28_rerun.py": "imports evolution.bridge_runner (DROP)",
    # KEEP in the manifest (default rule), but bridge-bound (README D-3).
    "src/alienclaw/diagnostics/scaling_experiment.py": "every entry point calls"
    " make_formula_bridge_runner, which decoupling.patch removes",
    "test/diagnostics/test_scaling_experiment.py": "tests scaling_experiment.py (above)",
    # KEEP in the manifest ("test outside the DROP test directories"), but each one
    # drives DROP code at runtime.
    "test/evolution/test_composition_evolution.py": "imports evolution.bridge_runner (DROP)",
    "test/evolution/test_end_to_end.py": "imports evolution.bridge_runner (DROP)",
    "test/evolution/test_main_cli.py": "tests run-experiment / run-scale-experiment, which"
    " decoupling.patch removes from evolution/__main__.py (README D-2)",
    "test/integration/end_to_end/live-submit-from-file.test.ts": "imports"
    " governance/common/leaderboard.js (DROP)",
    "test/integration/end_to_end/realistic-goal.test.ts": "assertion-free placeholder for"
    " the governance LLM path; the rest of test/integration/ is DROP",
    # REVIEW in the manifest ("no references found"): goal fixtures of the governance
    # integration tests (Packet 22). Nothing reads them once test/integration/ goes.
    "test/fixtures/test-goals/realistic-hn-summary.json": "goal fixture for"
    " realistic-goal.test.ts (above)",
    "test/fixtures/test-goals/synthetic-fox-count.json": "goal fixture for the DROP"
    " synthetic-goal.test.ts",
}

# Manifest-DROP files the kit keeps. The conformance files (fitness/conformance.py and
# its three tests, README D-1) are not here: the manifest already marks them KEEP.
# Nor is test/diagnostics/test_instrumentation.py (KEEP): decoupling.patch trims its two
# bridge-driven tests instead of deleting the file.
KIT_KEEPS = {
    "src/alienclaw/evolution/__main__.py": "decoupling.patch guts it: the bridge-backed"
    " subcommands go, migrate-pre-packet-16 stays (README D-2)",
    "src/alienclaw/index.ts": "decoupling.patch rewrites the barrel to export only"
    " constants and the genome codec",
    "src/alienclaw/telemetry/telemetry-writer.ts": "measured by the KEEP TypeScript gate"
    " in ci-pass2.patch; dropping it means re-measuring that gate (README D-8)",
    "test/telemetry/telemetry-writer.test.ts": "one of the 12 files the KEEP TypeScript"
    " gate names in ci-pass2.patch",
    "test/fixtures/api-contract-fixtures.json": "the API contract of the DEFER api/;"
    " test/api/validation-checksum.test.ts quotes a case from it. Goes with api/",
}


def git(repo: str, *args: str) -> str:
    out = subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(f"gen_delete_list.py: git {' '.join(args)} failed: {out.stderr.strip()}")
    return out.stdout


def base_blobs(repo: str, base: str) -> dict[str, str]:
    """path -> blob sha for every tracked file at BASE."""
    blobs = {}
    for rec in git(repo, "ls-tree", "-r", "-z", "--full-tree", base).split("\0"):
        if rec:
            meta, path = rec.split("\t", 1)
            blobs[path] = meta.split()[2]
    return blobs


def under_root(path: str, roots: list[str]) -> bool:
    return any(path.startswith(r) if r.endswith("/") else path == r for r in roots)


def patched_paths() -> set[str]:
    paths = set()
    for name in PATCHES:
        with open(os.path.join(KIT_DIR, name), encoding="utf-8") as fh:
            for line in fh:
                m = re.match(r"diff --git a/(\S+) b/(\S+)$", line.rstrip("\n"))
                if m:
                    paths.update(m.groups())
    return paths


def build(manifest: dict, blobs: dict[str, str]) -> tuple[list[str], list[str], list[str], int]:
    """Return (sorted delete list, errors, warnings, number of pass-1 additions)."""
    errors: list[str] = []
    warnings: list[str] = []
    files = {f["path"]: f for f in manifest["files"]}
    drop = {p for p, f in files.items() if f["verdict"] == "DROP"}

    for p in sorted(set(KIT_DECISIONS) & set(KIT_KEEPS)):
        errors.append(f"{p}: in both KIT_DECISIONS and KIT_KEEPS")
    for p in sorted(KIT_DECISIONS):
        if p not in files:
            errors.append(f"KIT_DECISIONS {p}: not in the manifest")
        elif p in drop:
            errors.append(f"KIT_DECISIONS {p}: stale, the manifest already marks it DROP")
        if p not in blobs:
            errors.append(f"KIT_DECISIONS {p}: missing at BASE")
    for p in sorted(KIT_KEEPS):
        if p not in drop:
            verdict = files[p]["verdict"] if p in files else "absent"
            errors.append(f"KIT_KEEPS {p}: stale, the manifest says {verdict}, not DROP")
        if p not in blobs:
            errors.append(f"KIT_KEEPS {p}: missing at BASE")

    for p in sorted(drop):
        if p not in blobs:
            if files[p]["pass1"] != "deleted-in-pass1":
                errors.append(f"manifest DROP {p}: missing at BASE and not a pass-1 deletion"
                              " (regenerate the manifest)")
        elif blobs[p] != files[p]["blob"]:
            warnings.append(f"manifest DROP {p}: blob at BASE differs from the manifest's")

    pass1_added = [p for p in manifest["pass1"]["added_in_pass1"]
                   if under_root(p, manifest["drop_roots"])]
    out = sorted((drop - set(KIT_KEEPS)) | set(KIT_DECISIONS) | set(pass1_added))
    out_set = set(out)

    for p in sorted(p for p, f in files.items() if f["pass1"] == "deleted-in-pass1"):
        if p not in out_set:
            errors.append(f"{p}: pass 1 deletes it, but the list keeps it")
    for p in sorted(patched_paths() & out_set):
        errors.append(f"{p}: a kit patch edits it, but the list deletes it")
    for p in out:
        if re.search(r"\s", p):
            errors.append(f"{p!r}: whitespace in path")
    return out, errors, warnings, len(pass1_added)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--repo", default=DEFAULT_REPO)
    ap.add_argument("--base", default=DEFAULT_BASE)
    ap.add_argument("--manifest", default=DEFAULT_MANIFEST)
    args = ap.parse_args(argv)

    with open(args.manifest, encoding="utf-8") as fh:
        manifest = json.load(fh)
    if manifest.get("schema_version") != "1.0":
        sys.exit(f"gen_delete_list.py: unexpected manifest schema {manifest.get('schema_version')}")

    out, errors, warnings, n_added = build(manifest, base_blobs(args.repo, args.base))
    for w in warnings:
        print(f"gen_delete_list.py: warning: {w}", file=sys.stderr)
    if errors:
        for e in errors:
            print(f"gen_delete_list.py: error: {e}", file=sys.stderr)
        return 1
    n_drop = sum(1 for f in manifest["files"] if f["verdict"] == "DROP")
    print(f"gen_delete_list.py: {len(out)} paths = {n_drop} manifest DROP - {len(KIT_KEEPS)}"
          f" KIT_KEEPS + {len(KIT_DECISIONS)} KIT_DECISIONS + {n_added} pass-1 addition(s)"
          f" (base {args.base})", file=sys.stderr)
    sys.stdout.write("".join(p + "\n" for p in out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
